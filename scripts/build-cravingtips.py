def norm(x):
    if isinstance(x, str):
        return {"text": x}
    d = {"text": x[0]}
    if len(x) > 1 and x[1]:
        d["ref"] = x[1]
    if len(x) > 2 and x[2]:
        d["tags"] = x[2].split(",")
    return d


